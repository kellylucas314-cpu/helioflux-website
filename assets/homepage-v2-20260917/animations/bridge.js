/* bridge.js
   A signal trace across the bridge band on the HelioFlux homepage, the dark navy
   slice that says "But there's a signal before there's a tumor." (styles in
   bridge.css).

   What it does: inserts one inline SVG into section.bridge-band, absolutely
   positioned across the full width: 140px tall and centered vertically on
   desktop, 90px tall and sitting under the two-line sentence at 768px and under
   (both set by the CSS). The SVG holds a single path:
   a nearly flat baseline with gentle, regular low humps across the left 65% of
   the width (the steady light of normal cells) that tightens, in the right 35%,
   into a denser, slightly taller cluster of oscillations (the signal). The path
   is generated by a deterministic function from a fixed seed, so the same width
   always gives the same trace; it is rebuilt from a ResizeObserver on the band
   whenever the band's width or the SVG's height changes, never per frame.

   When the band is 30% on screen (IntersectionObserver, once) the trace draws in
   from left to right over 2400ms with stroke-dasharray/dashoffset, eased on the
   site curve cubic-bezier(.22,.61,.36,1). Once drawn, a 2.5px photon with a soft
   cyan halo travels the path over 7s (positions sampled with getPointAtLength
   into a lookup table at rebuild time), fading in at the left edge, easing to a
   stop at the right edge and brightening a little as it reaches the signal
   cluster, then rests for 2s and goes again. On desktop a CSS mask on the SVG
   keeps the trace and the photon at 30% where they pass behind the text.

   Where it attaches: section.bridge-band only. The SVG is inserted just before
   the band's text wrapper, is aria-hidden, takes no pointer events and sits at
   z-index 1 (above the video and vignette, below the text). Nothing existing is
   changed. If the band is missing the script does nothing.

   How it pauses: everything runs on one requestAnimationFrame loop, and the loop
   is stopped when the band is off screen (IntersectionObserver), when the tab is
   hidden (visibilitychange) and when the visitor has paused motion on the site.
   The site signals that with the "helioflux:motion" event (detail.paused), but
   hero-motion.js fires the same event with paused true whenever the hero merely
   scrolls out of view, which is always the case while this band is showing. So,
   as progress.js and headlines.js do, the hero's own pause button is consulted
   one microtask later: aria-pressed "true" on a button that is actually shown
   means the visitor asked for stillness; otherwise the hero only left the screen
   and the trace carries on. A paused visitor who reaches the band gets the full
   trace at once (no draw-in) and no photon. prefers-reduced-motion: reduce gives
   the same still, finished trace, and a change in that preference either way is
   honored on the spot. devicePixelRatio needs no capping here: the drawing is
   vector, not canvas. */

(function () {
  'use strict';

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init, { once: true });
  } else {
    init();
  }

  function init() {
  var SEED = 20260917;
  var DRAW_MS = 2400;
  var TRAVEL_MS = 7000;
  var REST_MS = 2000;
  var DRAW_THRESHOLD = 0.3;
  var STEP = 2;          // px between points along x when building the path
  var TABLE_STEP = 2;    // px between samples along the path for the photon table
  var NS = 'http://www.w3.org/2000/svg';

  var doc = document;
  var band = doc.querySelector('section.bridge-band') || doc.querySelector('.bridge-band');
  if (!band) return;
  if (band.querySelector('.hf-bridge-trace')) return;

  var reduce = window.matchMedia ? window.matchMedia('(prefers-reduced-motion: reduce)') : null;
  var reduced = !!(reduce && reduce.matches);

  /* ---------- deterministic numbers ---------- */

  // mulberry32: small, seeded, good enough for shaping a line.
  function rng(seed) {
    var a = seed >>> 0;
    return function () {
      a = (a + 0x6D2B79F5) >>> 0;
      var t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  var random = rng(SEED);
  var FACTORS = [];   // per-cycle amplitude factors, 0..1
  var NOISE = [];     // value-noise lattice, 0..1
  var i;
  for (i = 0; i < 512; i++) FACTORS.push(random());
  for (i = 0; i < 1024; i++) NOISE.push(random());

  function smooth(t) { return t * t * (3 - 2 * t); }
  function smoothstep(a, b, x) {
    if (x <= a) return 0;
    if (x >= b) return 1;
    return smooth((x - a) / (b - a));
  }
  // Smooth value noise along x, one lattice point every 14px. Under a pixel of
  // wobble so the flat parts of the baseline are not ruler straight.
  function noise(x) {
    var p = x / 14;
    var i0 = Math.floor(p);
    var f = smooth(p - i0);
    var a = NOISE[((i0 % 1024) + 1024) % 1024];
    var b = NOISE[(((i0 + 1) % 1024) + 1024) % 1024];
    return a + (b - a) * f;
  }

  // The site's easing curve, cubic-bezier(.22,.61,.36,1), solved for y at x.
  function bezier(x1, y1, x2, y2) {
    function A(a1, a2) { return 1 - 3 * a2 + 3 * a1; }
    function B(a1, a2) { return 3 * a2 - 6 * a1; }
    function C(a1) { return 3 * a1; }
    function calc(t, a1, a2) { return ((A(a1, a2) * t + B(a1, a2)) * t + C(a1)) * t; }
    function slope(t, a1, a2) { return 3 * A(a1, a2) * t * t + 2 * B(a1, a2) * t + C(a1); }
    return function (x) {
      if (x <= 0) return 0;
      if (x >= 1) return 1;
      var t = x, k, s, cx;
      for (k = 0; k < 8; k++) {
        s = slope(t, x1, x2);
        if (s < 1e-6) break;
        cx = calc(t, x1, x2) - x;
        t -= cx / s;
      }
      return calc(t, y1, y2);
    };
  }
  var easeOut = bezier(0.22, 0.61, 0.36, 1);

  /* ---------- the trace ---------- */

  function buildPathData(W, H) {
    var y0 = H / 2;
    var A1 = H * 0.045;                                   // hump height: 6.3px at 140, 4px at 90
    var A2 = H * 0.105;                                   // cluster amplitude: 14.7px at 140, 9.5px at 90
    var P1 = Math.max(60, Math.min(124, W * 0.086));      // hump spacing: 124px at 1440, 60px at 390
    var P2 = Math.max(22, P1 * 0.27);                     // cluster spacing: 33px at 1440, 22px at 390
    var tStart = W * 0.61, tEnd = W * 0.69;               // where normal becomes signal
    var phase = 0;
    var parts = ['M0 ' + y0.toFixed(2)];
    for (var x = 0; ; x += STEP) {
      if (x > W) x = W;
      var s = smoothstep(tStart, tEnd, x);
      var period = P1 + (P2 - P1) * s;
      phase += (Math.PI * 2 * STEP) / period;
      var cycle = Math.floor(phase / (Math.PI * 2));
      var u = phase / (Math.PI * 2) - cycle;
      var f = FACTORS[cycle % FACTORS.length];
      // Normal cells: one soft hump per cycle, rising from the baseline.
      var hump = Math.exp(-Math.pow((u - 0.5) / 0.17, 2));
      var normal = -A1 * (0.72 + 0.28 * f) * hump;
      // The signal: oscillation both ways, more above the line than below,
      // with per-cycle variation so no two peaks match.
      var osc = Math.sin(phase);
      if (osc < 0) osc *= 0.55;
      var env = smoothstep(tStart, tEnd + W * 0.04, x);
      var signal = -A2 * (0.4 + 0.6 * f) * osc * env;
      var wobble = (noise(x) - 0.5) * 0.9;
      var y = y0 + (1 - s) * normal + s * signal + wobble;
      parts.push('L' + x.toFixed(1) + ' ' + y.toFixed(2));
      if (x >= W) break;
    }
    return parts.join('');
  }

  /* ---------- elements ---------- */

  var svg = doc.createElementNS(NS, 'svg');
  svg.setAttribute('class', 'hf-bridge-trace');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('preserveAspectRatio', 'none');

  var defs = doc.createElementNS(NS, 'defs');
  var grad = doc.createElementNS(NS, 'radialGradient');
  grad.setAttribute('id', 'hfBridgeHalo');
  var stops = [[0, 0.55], [0.4, 0.26], [1, 0]];
  for (i = 0; i < stops.length; i++) {
    var stop = doc.createElementNS(NS, 'stop');
    stop.setAttribute('offset', String(stops[i][0]));
    stop.setAttribute('stop-color', 'rgb(0,169,214)');
    stop.setAttribute('stop-opacity', String(stops[i][1]));
    grad.appendChild(stop);
  }
  defs.appendChild(grad);
  svg.appendChild(defs);

  var path = doc.createElementNS(NS, 'path');
  path.setAttribute('class', 'hf-bridge-trace__line');
  svg.appendChild(path);

  var photon = doc.createElementNS(NS, 'g');
  photon.setAttribute('class', 'hf-bridge-trace__photon');
  var halo = doc.createElementNS(NS, 'circle');
  halo.setAttribute('class', 'hf-bridge-trace__halo');
  halo.setAttribute('r', '11');
  var core = doc.createElementNS(NS, 'circle');
  core.setAttribute('class', 'hf-bridge-trace__core');
  core.setAttribute('r', '2.5');
  photon.appendChild(halo);
  photon.appendChild(core);
  svg.appendChild(photon);

  // Before the text wrapper (the band's positioned div that is not the vignette),
  // otherwise at the end. z-index decides the stacking either way.
  var wrapper = null;
  var kids = band.children;
  for (i = 0; i < kids.length; i++) {
    var kid = kids[i];
    if (kid.tagName === 'DIV' && !kid.hasAttribute('aria-hidden')) { wrapper = kid; break; }
  }
  if (wrapper) band.insertBefore(svg, wrapper); else band.appendChild(svg);

  /* ---------- state ---------- */

  var width = 0, height = 0;
  var length = 0;
  var table = null;       // Float32Array of x,y pairs every TABLE_STEP px along the path
  var tableCount = 0;
  var armed = false;      // the band reached 30% once
  var drawT = 0;          // 0..1 progress of the draw-in
  var drawn = false;
  var travelT = 0;        // ms into the current photon cycle
  var inView = false;
  var userPaused = false;
  var eventPaused = false;
  var frame = 0;
  var previous = 0;
  var curveOpacity = 0;

  function haloBoost(s) {
    // A touch brighter from the start of the cluster onwards.
    return 1 + 0.35 * smoothstep(0.62, 0.74, s);
  }

  function placePhoton(s, alpha) {
    if (!table || tableCount < 2) return;
    var pos = Math.max(0, Math.min(length, s * length)) / TABLE_STEP;
    var i0 = Math.min(tableCount - 2, Math.floor(pos));
    var f = pos - i0;
    var x = table[i0 * 2] + (table[i0 * 2 + 2] - table[i0 * 2]) * f;
    var y = table[i0 * 2 + 1] + (table[i0 * 2 + 3] - table[i0 * 2 + 1]) * f;
    photon.setAttribute('transform', 'translate(' + x.toFixed(2) + ' ' + y.toFixed(2) + ')');
    halo.setAttribute('r', (11 * haloBoost(s)).toFixed(2));
    if (alpha !== curveOpacity) {
      curveOpacity = alpha;
      photon.style.opacity = String(alpha.toFixed(3));
    }
  }

  function hidePhoton() {
    if (curveOpacity !== 0) {
      curveOpacity = 0;
      photon.style.opacity = '0';
    }
  }

  function applyDraw() {
    if (!length) return;
    if (drawT >= 1 || reduced) {
      path.style.strokeDasharray = 'none';
      path.style.strokeDashoffset = '0';
      return;
    }
    path.style.strokeDasharray = length + ' ' + length;
    path.style.strokeDashoffset = String(length * (1 - easeOut(drawT)));
  }

  function rebuild(W, H) {
    width = W;
    height = H;
    svg.setAttribute('viewBox', '0 0 ' + W + ' ' + H);
    path.setAttribute('d', buildPathData(W, H));
    length = 0;
    try { length = path.getTotalLength(); } catch (e) { length = 0; }
    if (!length || !isFinite(length)) {
      table = null;
      tableCount = 0;
      return;
    }
    tableCount = Math.floor(length / TABLE_STEP) + 2;
    table = new Float32Array(tableCount * 2);
    for (var k = 0; k < tableCount; k++) {
      var p = path.getPointAtLength(Math.min(length, k * TABLE_STEP));
      table[k * 2] = p.x;
      table[k * 2 + 1] = p.y;
    }
    // Before the draw the trace is fully hidden (offset equals length), during
    // and after it the current progress is reapplied to the new length.
    if (!armed && !reduced) {
      path.style.strokeDasharray = length + ' ' + length;
      path.style.strokeDashoffset = String(length);
    } else {
      applyDraw();
    }
    if (drawn && !reduced) {
      var cycle = travelT % (TRAVEL_MS + REST_MS);
      if (cycle < TRAVEL_MS) placePhoton(travelPosition(cycle / TRAVEL_MS), travelAlpha(cycle / TRAVEL_MS));
    }
  }

  function measure() {
    var W = Math.round(band.clientWidth || band.getBoundingClientRect().width);
    var H = Math.round(svg.getBoundingClientRect().height) || (W <= 768 ? 90 : 140);
    if (W < 2 || H < 2) return;
    if (W === width && H === height) return;
    rebuild(W, H);
  }

  /* ---------- motion ---------- */

  // Quick off the left edge, easing to a stop at the right edge, where the
  // signal is. Distance along the path as a fraction, for time fraction t.
  function travelPosition(t) {
    return 1 - Math.pow(1 - t, 1.45);
  }
  function travelAlpha(t) {
    var fadeIn = Math.min(1, t / 0.07);
    var fadeOut = Math.min(1, (1 - t) / 0.08);
    return Math.max(0, Math.min(fadeIn, fadeOut));
  }

  function allowed() {
    return inView && !doc.hidden && !userPaused && !reduced;
  }

  function finishNow() {
    drawT = 1;
    drawn = true;
    applyDraw();
    hidePhoton();
  }

  function tick(now) {
    frame = 0;
    if (!armed || !allowed()) return;
    var dt = previous ? Math.min(now - previous, 50) : 0;
    previous = now;
    if (!drawn) {
      drawT = Math.min(1, drawT + dt / DRAW_MS);
      applyDraw();
      if (drawT >= 1) {
        drawn = true;
        travelT = 0;
      }
    } else {
      travelT += dt;
      var cycle = travelT % (TRAVEL_MS + REST_MS);
      if (cycle < TRAVEL_MS) {
        var t = cycle / TRAVEL_MS;
        placePhoton(travelPosition(t), travelAlpha(t));
      } else {
        hidePhoton();
      }
    }
    frame = window.requestAnimationFrame(tick);
  }

  function sync() {
    if (frame) { window.cancelAnimationFrame(frame); frame = 0; }
    previous = 0;
    if (!armed) return;
    if (reduced) { finishNow(); return; }
    if (userPaused && !drawn) { finishNow(); }
    if (!allowed()) { if (drawn) hidePhoton(); return; }
    frame = window.requestAnimationFrame(tick);
  }

  function arm() {
    if (armed) return;
    armed = true;
    if (!length) measure();
    if (reduced || userPaused) { finishNow(); return; }
    drawT = 0;
    sync();
  }

  /* ---------- pausing conventions ---------- */

  function pauseButton() {
    return doc.querySelector('.cell-pause[aria-pressed]');
  }
  // Pressed, and something a visitor could actually have pressed. The current
  // stylesheet hides the hero's button, and hero-motion.js also presses it by
  // itself when the hero video's play() rejects. A control nobody can see cannot
  // carry the visitor's choice.
  function visitorPressed(button) {
    if (button.getAttribute('aria-pressed') !== 'true') return false;
    var cs = window.getComputedStyle(button);
    return cs.display !== 'none' && cs.visibility !== 'hidden';
  }
  function applyMotionEvent() {
    var button = pauseButton();
    var was = userPaused;
    if (!eventPaused) userPaused = false;
    else if (button) userPaused = visitorPressed(button);
    else userPaused = true;
    if (was !== userPaused) sync();
  }
  function afterCurrentTask(fn) {
    if (typeof Promise === 'function') Promise.resolve().then(fn);
    else window.setTimeout(fn, 0);
  }

  window.addEventListener('helioflux:motion', function (event) {
    eventPaused = !!(event && event.detail && event.detail.paused);
    afterCurrentTask(applyMotionEvent);
  });
  doc.addEventListener('visibilitychange', sync);

  if (reduce) {
    var onReduce = function () {
      reduced = !!reduce.matches;
      svg.classList.toggle('is-reduced', reduced);
      if (reduced) { if (armed) finishNow(); else applyDraw(); }
      else if (armed && length) { applyDraw(); }
      else if (length) {
        // Preference switched off before the band ever armed: hide the trace
        // again so the draw-in later starts from nothing instead of snapping
        // the full line away first.
        path.style.strokeDasharray = length + ' ' + length;
        path.style.strokeDashoffset = String(length);
      }
      sync();
    };
    if (typeof reduce.addEventListener === 'function') reduce.addEventListener('change', onReduce);
    else if (typeof reduce.addListener === 'function') reduce.addListener(onReduce);
  }

  var initialButton = pauseButton();
  if (initialButton && visitorPressed(initialButton)) userPaused = true;

  /* ---------- observers ---------- */

  if ('IntersectionObserver' in window) {
    new IntersectionObserver(function (entries) {
      var k, entry;
      for (k = 0; k < entries.length; k++) {
        entry = entries[k];
        inView = entry.isIntersecting;
        if (entry.isIntersecting && entry.intersectionRatio >= DRAW_THRESHOLD) arm();
      }
      sync();
    }, { threshold: [0, DRAW_THRESHOLD] }).observe(band);
  } else {
    inView = true;
    arm();
  }

  if ('ResizeObserver' in window) {
    // The band for width changes, the SVG itself for its CSS height (which can
    // arrive after the script if the stylesheet loads late). Neither rebuild
    // changes either box, so this cannot loop.
    var ro = new ResizeObserver(function () { measure(); });
    ro.observe(band);
    ro.observe(svg);
  } else {
    window.addEventListener('resize', measure, { passive: true });
  }

  svg.classList.toggle('is-reduced', reduced);
  measure();
  if (reduced) applyDraw();
  }
})();
